/** Writes the synthetic corpus to data/. Deterministic apart from PDF/XLSX container metadata. */
import fs from "node:fs";
import path from "node:path";
import { buildCorpus } from "../src/lib/seed/corpus";

const root = path.resolve("data");
fs.rmSync(root, { recursive: true, force: true });
const files = await buildCorpus();
const manifest: { path: string; sourceId: string; bytes: number }[] = [];
for (const f of files) {
  const full = path.join(root, f.path);
  fs.mkdirSync(path.dirname(full), { recursive: true });
  fs.writeFileSync(full, f.content);
  manifest.push({ path: f.path, sourceId: f.sourceId, bytes: Buffer.byteLength(f.content) });
}
fs.writeFileSync(path.join(root, "manifest.json"), JSON.stringify(manifest, null, 2) + "\n");
fs.writeFileSync(path.join(root, "README.md"), "# Synthetic corpus\n\nEvery person, address, email and incident in this folder is fictional. Files are generated by `npm run data:generate` from `src/lib/seed/corpus*.ts` and imported by `npm run seed`.\n");
console.log(`wrote ${files.length} files to ${root}`);
